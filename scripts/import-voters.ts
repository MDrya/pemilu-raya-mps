// Builds private/voters.sql from private/voters.csv (the real DPT).
//
//   npm run voters:import
//
// private/ is git-ignored: real student names and NIMs must never be committed
// (the repository is public). The CSV has the header `nim,angkatan,nama`.
//
// Checks: NIM is 8 digits and matches the angkatan (173YYxxx), no NIM appears
// twice. Exact duplicate rows are dropped with a warning. Names are tidied:
// all-lowercase words get a capital first letter; ALL-CAPS names become Title Case.

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const csvPath = fileURLToPath(new URL('../private/voters.csv', import.meta.url))
const sqlPath = fileURLToPath(new URL('../private/voters.sql', import.meta.url))
const PROGRAM_CODE = '173' // Desain Interior ITB

const capitalize = (word: string) =>
  // Also capitalize after dots, so "m.i" becomes "M.I".
  word.replace(/(^|\.)([a-z])/g, (_, dot: string, letter: string) => dot + letter.toUpperCase())

function tidyName(raw: string) {
  const name = raw.trim().replace(/\s+/g, ' ')
  const allCaps = name === name.toUpperCase() && /[A-Z]/.test(name)
  return name
    .split(' ')
    .map((word) => {
      if (allCaps) return capitalize(word.toLowerCase())
      if (word === word.toLowerCase()) return capitalize(word)
      return word // mixed case (e.g. "AM", "McX") is left as written
    })
    .join(' ')
}

const sql = (value: string) => `'${value.replaceAll("'", "''")}'`

const lines = readFileSync(csvPath, 'utf8').split(/\r?\n/).filter((l) => l.trim())
const header = lines.shift()?.trim()
if (header !== 'nim,angkatan,nama') throw new Error(`Unexpected header "${header}" (expected nim,angkatan,nama)`)

const errors: string[] = []
const warnings: string[] = []
const byNim = new Map<string, { nim: string; angkatan: number; nama: string }>()

lines.forEach((line, i) => {
  const row = i + 2
  const [nim, angkatanText, ...nameParts] = line.split(',').map((s) => s.trim())
  const raw = nameParts.join(',')
  const angkatan = Number(angkatanText)
  if (!/^\d{8}$/.test(nim)) return errors.push(`row ${row}: NIM "${nim}" is not 8 digits`)
  if (!Number.isInteger(angkatan)) return errors.push(`row ${row}: angkatan "${angkatanText}" is not a number`)
  if (!nim.startsWith(`${PROGRAM_CODE}${String(angkatan).padStart(2, '0')}`)) {
    return errors.push(`row ${row}: NIM ${nim} does not match angkatan ${angkatan}`)
  }
  if (!raw) return errors.push(`row ${row}: empty name`)

  const nama = tidyName(raw)
  const existing = byNim.get(nim)
  if (existing) {
    if (existing.nama === nama && existing.angkatan === angkatan) warnings.push(`row ${row}: duplicate of ${nim}, skipped`)
    else errors.push(`row ${row}: NIM ${nim} is used by both "${existing.nama}" and "${nama}"`)
    return
  }
  if (nama !== raw.trim()) warnings.push(`row ${row}: tidied "${raw.trim()}" → "${nama}"`)
  byNim.set(nim, { nim, angkatan, nama })
})

for (const w of warnings) console.log(`  note  ${w}`)
if (errors.length) {
  for (const e of errors) console.error(`  ERROR ${e}`)
  console.error(`\n${errors.length} error(s): fix private/voters.csv and run again. Nothing was written.`)
  process.exit(1)
}

const voters = [...byNim.values()].sort((a, b) => a.nim.localeCompare(b.nim))
const perAngkatan = new Map<number, typeof voters>()
for (const v of voters) perAngkatan.set(v.angkatan, [...(perAngkatan.get(v.angkatan) ?? []), v])

const output = `-- =============================================================================
-- PEMIRA — real voter list (DPT)
-- GENERATED by scripts/import-voters.ts from private/voters.csv.
-- Contains real student data: keep it in private/ and NEVER commit it.
--
-- Replaces every voter. Refuses to run once any vote has been recorded:
-- use Reset Demo first (only while demo tools are still enabled).
-- =============================================================================

-- Safety check first, outside the transaction, so a refusal leaves nothing open.
do $$
begin
  if (select coalesce(sum(vote_count), 0) from public.tally) > 0
     or exists (select 1 from public.voters where status <> 'belum') then
    raise exception 'Masih ada suara tercatat. Jalankan Reset Demo dulu, lalu ulangi.';
  end if;
end $$;

begin;

delete from public.booth_assignments where true;
update public.booths set status = 'terkunci', unlocked_at = null where true;
delete from public.voters where true;

-- ${voters.length} voters: ${[...perAngkatan].map(([a, list]) => `angkatan ${a} = ${list.length}`).join(', ')}
insert into public.voters (nim, angkatan, nama)
values
${voters.map((v) => `  (${sql(v.nim)}, ${v.angkatan}, ${sql(v.nama)})`).join(',\n')};

update public.public_turnout set total_dpt = (select count(*) from public.voters) where id = 1;

commit;

-- Check: voters per angkatan.
select angkatan, count(*) as pemilih from public.voters group by angkatan order by angkatan;
`

writeFileSync(sqlPath, output)
console.log(`\nWrote ${sqlPath}`)
console.log(`${voters.length} voters — ${[...perAngkatan].map(([a, list]) => `angkatan ${a}: ${list.length}`).join(', ')}`)
